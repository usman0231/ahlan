/* eslint-env node */
/**
 * Renders the client's logo to the PNGs Expo needs (the in-app logo, app icon,
 * Android adaptive foreground, splash and favicon) and to the small embedded
 * copy the API puts on report PDF covers.
 *
 *   pnpm --filter mobile brand:render
 *
 * Source: assets/brand/logo-source.jpg (the client's artwork, on white). The
 * ball's white panels are part of the drawing, so the background cannot be
 * keyed out; the logo always sits on a white tile instead.
 *
 * Uses playwright-core (already in the workspace for PDF rendering) driving an
 * installed Chrome, so no extra browser download is needed. Point CHROME_PATH
 * at another Chromium if Chrome lives elsewhere.
 */
const { chromium } = require('playwright-core');
const fs = require('fs');
const path = require('path');

const out = path.join(__dirname, '..', 'assets', 'brand');
const source = `data:image/jpeg;base64,${fs
  .readFileSync(path.join(out, 'logo-source.jpg'))
  .toString('base64')}`;

/** Logo centred in a white box; `inset` is the share of the box left as margin. */
const tile = (size, radius, inset, logo) => `
<div style="width:${size}px;height:${size}px;border-radius:${radius}px;background:#FFFFFF;
  display:flex;align-items:center;justify-content:center;">
  <img src="${logo}" style="width:${Math.round(size * (1 - 2 * inset))}px;height:auto;">
</div>`;

(async () => {
  const browser = await chromium.launch({
    executablePath:
      process.env.CHROME_PATH ??
      (process.platform === 'win32'
        ? 'C:/Program Files/Google/Chrome/Application/chrome.exe'
        : process.platform === 'darwin'
          ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
          : '/usr/bin/google-chrome'),
  });
  const page = await browser.newPage({ deviceScaleFactor: 1 });

  // Trim the source's white margin so every asset can size the logo by its
  // own bounds.
  const logo = await page.evaluate(async (src) => {
    const img = new Image();
    img.src = src;
    await img.decode();
    const c = document.createElement('canvas');
    c.width = img.width;
    c.height = img.height;
    const ctx = c.getContext('2d');
    ctx.drawImage(img, 0, 0);
    const { data, width, height } = ctx.getImageData(0, 0, c.width, c.height);
    let x0 = width, y0 = height, x1 = 0, y1 = 0;
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        const i = (y * width + x) * 4;
        if (Math.min(data[i], data[i + 1], data[i + 2]) < 235) {
          x0 = Math.min(x0, x); y0 = Math.min(y0, y);
          x1 = Math.max(x1, x); y1 = Math.max(y1, y);
        }
      }
    }
    const o = document.createElement('canvas');
    o.width = x1 - x0 + 1;
    o.height = y1 - y0 + 1;
    const octx = o.getContext('2d');
    octx.fillStyle = '#FFFFFF';
    octx.fillRect(0, 0, o.width, o.height);
    octx.drawImage(c, x0, y0, o.width, o.height, 0, 0, o.width, o.height);
    return o.toDataURL('image/png');
  }, source);
  fs.writeFileSync(path.join(out, 'logo.png'), Buffer.from(logo.split(',')[1], 'base64'));
  console.log('wrote logo.png');

  // Report PDFs are rendered from one self-contained HTML string, so the logo
  // travels inside it as a data URI - a small JPEG, it prints at ~40mm.
  const pdfLogo = await page.evaluate(async (src) => {
    const img = new Image();
    img.src = src;
    await img.decode();
    const c = document.createElement('canvas');
    c.width = 360;
    c.height = Math.round((img.height / img.width) * 360);
    c.getContext('2d').drawImage(img, 0, 0, c.width, c.height);
    return c.toDataURL('image/jpeg', 0.85);
  }, logo);
  const apiLogo = path.join(__dirname, '..', '..', 'api', 'src', 'modules', 'reports', 'templates', 'logo.generated.ts');
  fs.writeFileSync(
    apiLogo,
    '// Generated by `pnpm --filter mobile brand:render` from apps/mobile/assets/brand/logo-source.jpg. Do not edit.\n' +
      `export const LOGO_DATA_URI =\n  '${pdfLogo}';\n`,
  );
  console.log('wrote api logo.generated.ts');

  const jobs = [
    { file: 'icon.png', size: 1024, html: tile(1024, 0, 0.12, logo) },          // stores round it themselves
    { file: 'adaptive-icon.png', size: 1024, html: tile(1024, 0, 0.24, logo) }, // Android safe zone
    { file: 'splash-icon.png', size: 1024, html: tile(1024, 220, 0.1, logo) },
    { file: 'favicon.png', size: 192, html: tile(192, 44, 0.08, logo) },
  ];
  for (const job of jobs) {
    await page.setViewportSize({ width: job.size, height: job.size });
    await page.setContent(`<html><body style="margin:0;background:transparent">${job.html}</body></html>`);
    await page.waitForFunction(() => [...document.images].every((i) => i.complete));
    await page.screenshot({
      path: path.join(out, job.file),
      omitBackground: true,
      clip: { x: 0, y: 0, width: job.size, height: job.size },
    });
    console.log('wrote', job.file);
  }
  await browser.close();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
